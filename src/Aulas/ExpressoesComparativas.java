package Aulas;

public class ExpressoesComparativas {
    public static void main(String[] args) {

        int numeroUm = 2;
        int numeroDois = 4;

        System.out.println(numeroUm == numeroDois);
        System.out.println(numeroUm != numeroDois);
        System.out.println(numeroUm > numeroDois);
        System.out.println(numeroUm < numeroDois);
        System.out.println(numeroUm >= numeroDois);
        System.out.println(numeroUm <= numeroDois);
    }
}
