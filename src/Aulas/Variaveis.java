package Aulas;

public class Variaveis {
    public static void main(String[] args) {
        int idade = 25;
        double salarioMensal = 4500.00;
        char genero = 'M';
        boolean empregadoJava = true;

        System.out.println("Idade: " + idade + " anos.");
        System.out.println("Salário Mensal: R$" + salarioMensal + " reais mensais.");
        System.out.println("Gênero: " + genero + "asculino");
        System.out.println("Empregado: " + empregadoJava);

    }
}

